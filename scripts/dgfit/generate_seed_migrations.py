#!/usr/bin/env python3
"""Generate DG FIT seed migrations from the JSON data in ./data.

  python3 scripts/dgfit/generate_seed_migrations.py

Writes SparkyFitnessServer/db/migrations/2026103011*_dgfit_seed_*.sql. Rows get
deterministic UUIDs (uuid5) and ON CONFLICT DO NOTHING, so re-running a
migration never duplicates or overwrites anything a user changed.
"""
import json
import pathlib
import uuid

HERE = pathlib.Path(__file__).resolve().parent
DATA = HERE / 'data'
MIGRATIONS = HERE.parent.parent / 'SparkyFitnessServer' / 'db' / 'migrations'
NS = uuid.UUID('6f1d2a3e-9b7c-4d1e-8f5a-0c2b4e6d8a10')


def q(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'TRUE' if value else 'FALSE'
    if isinstance(value, (int, float)):
        return repr(round(float(value), 3))
    return "'" + str(value).replace("'", "''") + "'"


def foods_sql():
    seen, foods = set(), []
    for name in ('foods_a.json', 'foods_b.json'):
        for item in json.loads((DATA / name).read_text()):
            key = item['name'].strip().lower()
            if key in seen:
                continue
            seen.add(key)
            foods.append(item)

    out = [
        '-- DG FIT: shared Turkish food library (generated by',
        '-- scripts/dgfit/generate_seed_migrations.py). Values per 100 g / 100 ml',
        '-- plus common portions; visible to every user (shared_with_public).',
        '',
    ]
    for item in foods:
        fid = uuid.uuid5(NS, 'food:' + item['name'])
        unit = item.get('unit', 'g')
        n = item['per100g']
        out.append(
            'INSERT INTO foods (id, name, user_id, is_custom, shared_with_public, provider_verified, notes) VALUES '
            f"({q(str(fid))}, {q(item['name'])}, NULL, FALSE, TRUE, TRUE, 'DG FIT temel besin listesi') ON CONFLICT (id) DO NOTHING;"
        )
        variants = [(100.0, unit, 1.0, True)]
        for p in item.get('portions', []):
            label = p['label'].strip()
            if label.startswith('1 '):
                label = label[2:]
            if '(' not in label:
                label = f"{label} ({int(p['grams']) if float(p['grams']).is_integer() else p['grams']} {unit})"
            variants.append((1.0, label, p['grams'] / 100.0, False))
        for size, sunit, factor, default in variants:
            vid = uuid.uuid5(NS, f'variant:{item["name"]}:{sunit}')
            def v(k):
                return q(round((n.get(k) or 0) * factor, 2))
            out.append(
                'INSERT INTO food_variants (id, food_id, serving_size, serving_unit, calories, protein, carbs, fat, '
                'dietary_fiber, sugars, saturated_fat, sodium, alcohol_g, is_default, source) VALUES '
                f'({q(str(vid))}, {q(str(fid))}, {q(size)}, {q(sunit)}, {v("calories")}, {v("protein")}, {v("carbs")}, '
                f'{v("fat")}, {v("fiber")}, {v("sugar")}, {v("saturated_fat")}, {v("sodium_mg")}, {v("alcohol")}, '
                f"{q(default)}, 'imported') ON CONFLICT (id) DO NOTHING;"
            )
    return '\n'.join(out) + '\n', len(foods)


def modality(category, equipment):
    if (category or '').lower() == 'cardio':
        return 'duration_distance'
    if equipment and equipment.strip().lower() == 'body only':
        return 'bodyweight_reps'
    return 'weight_reps'


CALORIES_PER_HOUR = {
    'strength': 360, 'powerlifting': 360, 'olympic weightlifting': 420,
    'strongman': 480, 'plyometrics': 480, 'cardio': 600, 'stretching': 150,
}


def exercises_sql():
    source = json.loads((DATA / 'free_exercise_db.json').read_text())
    tr = json.loads((DATA / 'exercises_tr.json').read_text())
    out = [
        '-- DG FIT: shared exercise library from free-exercise-db (Unlicense,',
        '-- github.com/yuhonas/free-exercise-db) with Turkish names and steps',
        '-- (generated by scripts/dgfit/generate_seed_migrations.py). System rows:',
        '-- user_id NULL, visible to everyone. Images are fetched on first view by',
        '-- the /uploads/exercises/:id/:file route.',
        '',
    ]
    for x in source:
        t = tr[x['id']]
        eid = uuid.uuid5(NS, 'exercise:' + x['id'])
        cols = {
            'id': str(eid),
            'source': 'free-exercise-db',
            'source_id': x['id'],
            'name': t['name'],
            'force': x.get('force'),
            'level': x.get('level'),
            'mechanic': x.get('mechanic'),
            'equipment': json.dumps([x['equipment']] if x.get('equipment') else [], ensure_ascii=False),
            'primary_muscles': json.dumps(x.get('primaryMuscles') or [], ensure_ascii=False),
            'secondary_muscles': json.dumps(x.get('secondaryMuscles') or [], ensure_ascii=False),
            'instructions': json.dumps(t['instructions'], ensure_ascii=False),
            'category': x.get('category'),
            'images': json.dumps(x.get('images') or [], ensure_ascii=False),
            'calories_per_hour': CALORIES_PER_HOUR.get(x.get('category'), 300),
            'description': x['name'],
            'is_custom': False,
            'user_id': None,
            'shared_with_public': True,
            'modality': modality(x.get('category'), x.get('equipment')),
        }
        out.append(
            f"INSERT INTO exercises ({', '.join(cols)}, created_at, updated_at) VALUES "
            f"({', '.join(q(v) for v in cols.values())}, now(), now()) ON CONFLICT (id) DO NOTHING;"
        )
    return '\n'.join(out) + '\n', len(source)


if __name__ == '__main__':
    sql, n = foods_sql()
    (MIGRATIONS / '20261030110000_dgfit_seed_turkish_foods.sql').write_text(sql)
    print('foods', n)
    if (DATA / 'exercises_tr.json').exists():
        sql, n = exercises_sql()
        (MIGRATIONS / '20261030110100_dgfit_seed_exercise_library.sql').write_text(sql)
        print('exercises', n)
